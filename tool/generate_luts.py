"""Generates the bundled 3D LUTs (Adobe .cube, size 17) in assets/luts/."""
import colorsys, os

N = 17
OUT = os.path.join(os.path.dirname(__file__), '..', 'assets', 'luts')

def clamp(v): return max(0.0, min(1.0, v))
def luma(r, g, b): return 0.2126*r + 0.7152*g + 0.0722*b

def teal_orange(r, g, b):
    l = luma(r, g, b)
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    # push skin/warm hues to orange, everything cool to teal
    warm = 1.0 if (h < 0.14 or h > 0.92) else 0.0
    tr, tg, tb = (1.0, 0.62, 0.32) if warm else (0.2, 0.62, 0.68)
    k = 0.35 * s + 0.15
    r, g, b = r + (tr * l - r) * k * 0.6, g + (tg * l - g) * k * 0.6, b + (tb * l - b) * k * 0.6
    # shadows teal, highlights orange
    r += (l - 0.5) * 0.08; b -= (l - 0.5) * 0.08
    return r, g, b

def bleach_bypass(r, g, b):
    l = luma(r, g, b)
    def overlay(a, m): return 2*a*m if a < 0.5 else 1 - 2*(1-a)*(1-m)
    r2, g2, b2 = overlay(r, l), overlay(g, l), overlay(b, l)
    return [0.35*c + 0.65*(0.5*c2 + 0.5*l) for c, c2 in ((r, r2), (g, g2), (b, b2))]

def warm_film(r, g, b):
    def curve(x): return 0.06 + 0.9 * (x*x*(3-2*x)*0.6 + x*0.4)
    return curve(r)*1.04, curve(g)*1.0, curve(b)*0.9 + 0.03

for name, fn in [('teal_orange', teal_orange), ('bleach_bypass', bleach_bypass), ('warm_film', warm_film)]:
    lines = [f'# Lumora Studio built-in LUT, generated by tool/generate_luts.py', f'TITLE "{name}"', f'LUT_3D_SIZE {N}', 'DOMAIN_MIN 0.0 0.0 0.0', 'DOMAIN_MAX 1.0 1.0 1.0']
    for bi in range(N):
        for gi in range(N):
            for ri in range(N):
                r, g, b = fn(ri/(N-1), gi/(N-1), bi/(N-1))
                lines.append(f'{clamp(r):.6f} {clamp(g):.6f} {clamp(b):.6f}')
    open(os.path.join(OUT, name + '.cube'), 'w').write('\n'.join(lines) + '\n')
    print('wrote', name)
